@dataclass
class SpacetimeCheck:
    """
    Represents one Controlled-Pauli spacetime check.

    A check lives at time-layer `t_layer` and ties ancilla qubit `ancilla_idx`
    to data qubit `data_idx` via a Pauli operator (X, Y, or Z).

    In a real spacetime code the ancilla accumulates XOR-parity of all data
    qubits it is entangled with across consecutive time layers – this gives us
    "spacetime separation" Δt.
    """
    ancilla_idx: int        # which ancilla (0-based)
    data_idx:    int        # which data qubit (0-based)
    pauli:       str        # "X", "Y", or "Z"
    t_layer:     int        # time layer at which the check fires

    def __repr__(self):
        return (f"Check(a{self.ancilla_idx}→d{self.data_idx}, "
                f"P={self.pauli}, t={self.t_layer})")


class SpacetimeSyndromeEngine:
    """
    Fallback implementation of the qiskit-paulice syndrome-extraction engine.

    Tracks a (N_DATA + N_ANCILLA)-qubit state vector using numpy.
    Supports:
      • apply_1q(gate, qubit)   – apply a 1-qubit gate matrix
      • apply_cx(ctrl, tgt)     – CNOT
      • apply_check(check)      – Controlled-Pauli from SpacetimeCheck
      • measure_ancillas()      – collapses ancillas, returns bit-string
      • reset_ancillas()        – reset ancillas to |0⟩ for next syndrome round
    """

    # ── standard gate matrices ────────────────────────────────────────────
    _H  = (1/np.sqrt(2)) * np.array([[1,  1], [ 1, -1]], dtype=complex)
    _X  = np.array([[0, 1], [1,  0]], dtype=complex)
    _Y  = np.array([[0,-1j],[1j, 0]], dtype=complex)
    _Z  = np.array([[1, 0], [0, -1]], dtype=complex)
    _S  = np.array([[1, 0], [0,  1j]], dtype=complex)
    _T  = np.array([[1, 0], [0,  np.exp(1j*np.pi/4)]], dtype=complex)
    _Rx = staticmethod(lambda θ: np.cos(θ/2)*np.eye(2)
                       - 1j*np.sin(θ/2)*np.array([[0,1],[1,0]], dtype=complex))
    _Ry = staticmethod(lambda θ: np.cos(θ/2)*np.eye(2)
                       - 1j*np.sin(θ/2)*np.array([[0,-1j],[1j,0]], dtype=complex))
    _Rz = staticmethod(lambda θ: np.array(
            [[np.exp(-1j*θ/2), 0],[0, np.exp(1j*θ/2)]], dtype=complex))

    def __init__(self, n_qubits: int, seed: int = 42):
        self.n = n_qubits
        self.rng = np.random.default_rng(seed)
        self.state = np.zeros(2**n_qubits, dtype=complex)
        self.state[0] = 1.0          # |00…0⟩

    # ── single-qubit gate (full-register tensor product) ─────────────────
    def apply_1q(self, gate: np.ndarray, qubit: int):
        """
        Embed a 2×2 gate on `qubit` into the full 2^n state-vector space.
        Uses the standard 'reshape-multiply-reshape' trick.
        """
        s = self.state.reshape([2]*self.n)
        s = np.tensordot(gate, s, axes=([1], [qubit]))
        # tensordot puts the new axis at position 0 – move it back
        s = np.moveaxis(s, 0, qubit)
        self.state = s.reshape(-1)

    # ── two-qubit CNOT ────────────────────────────────────────────────────
    def apply_cx(self, ctrl: int, tgt: int):
        """
        Apply CNOT: flip `tgt` whenever `ctrl` is |1⟩.
        Works directly on the amplitude vector.
        """
        s = self.state.reshape([2]*self.n)
        # Slice where ctrl==1, then swap the target amplitudes
        idx_ctrl1 = [slice(None)]*self.n
        idx_ctrl1[ctrl] = 1
        idx_ctrl1 = tuple(idx_ctrl1)

        sub = s[idx_ctrl1]            # shape [2]*( n-1 ) effectively
        # swap target dimension (now shifted by 1 if tgt > ctrl)
        tgt_in_sub = tgt if tgt < ctrl else tgt - 1
        # Swap 0 ↔ 1 along tgt_in_sub axis  (= apply X on sub-tensor)
        s[idx_ctrl1] = np.flip(sub, axis=tgt_in_sub)
        self.state = s.reshape(-1)

    # ── Controlled-Pauli (the core qiskit-paulice primitive) ─────────────
    def apply_check(self, check: SpacetimeCheck,
                    ancilla_offset: int = N_DATA):
        """
        Apply Controlled-Pauli: ancilla qubit is the control, data qubit is
        the target. Depending on `check.pauli`:
          CX → CNOT
          CY → ancilla controls Y on data  (= S†·CNOT·S on target, modulo phase)
          CZ → Controlled-Z
        This is the building block of spacetime syndrome extraction.
        """
        ctrl = ancilla_offset + check.ancilla_idx
        tgt  = check.data_idx
        P    = check.pauli

        if P == "X":
            # standard Hadamard-basis parity check
            self.apply_1q(self._H, ctrl)
            self.apply_cx(ctrl, tgt)
            self.apply_1q(self._H, ctrl)
        elif P == "Y":
            # CY = (S†⊗I)·CX·(S⊗I) up to global phase – sufficient for
            # syndrome extraction because we only care about the ancilla bit
            self.apply_1q(self._S.conj().T, tgt)
            self.apply_cx(ctrl, tgt)
            self.apply_1q(self._S, tgt)
        elif P == "Z":
            # CZ via basis change on target
            self.apply_1q(self._H, tgt)
            self.apply_cx(ctrl, tgt)
            self.apply_1q(self._H, tgt)
        else:
            raise ValueError(f"Unknown Pauli '{P}'")

    # ── measure ancillas ──────────────────────────────────────────────────
    def measure_ancillas(self, ancilla_offset: int = N_DATA,
                         readout_err: float = 0.0) -> str:
        """
        Project each ancilla qubit onto the Z-basis.
        Returns a bit-string of length N_ANCILLA, e.g. '0101'.
        Optionally flips each bit with probability `readout_err`.
        """
        bits = []
        for q in range(N_ANCILLA):
            qubit = ancilla_offset + q
            prob1 = self._prob1(qubit)
            outcome = int(self.rng.random() < prob1)
            # ── readout error ──
            if self.rng.random() < readout_err:
                outcome ^= 1
            bits.append(str(outcome))
            # ── collapse ──
            self._project(qubit, outcome)
        return "".join(bits)

    def _prob1(self, qubit: int) -> float:
        """Marginal probability of qubit being in state |1⟩."""
        s = self.state.reshape([2]*self.n)
        idx1 = [slice(None)]*self.n
        idx1[qubit] = 1
        return float(np.sum(np.abs(s[tuple(idx1)])**2))

    def _project(self, qubit: int, outcome: int):
        """Collapse state onto |outcome⟩ for the given qubit."""
        s = self.state.reshape([2]*self.n)
        # Zero out the other outcome
        other = 1 - outcome
        idx = [slice(None)]*self.n
        idx[qubit] = other
        s[tuple(idx)] = 0.0
        # Renormalise
        norm = np.linalg.norm(s)
        if norm > 1e-12:
            s /= norm
        self.state = s.reshape(-1)

    def reset_ancillas(self, ancilla_offset: int = N_DATA):
        """Reset all ancilla qubits to |0⟩ by projection."""
        for q in range(N_ANCILLA):
            self._project(ancilla_offset + q, 0)

    def get_data_state(self) -> np.ndarray:
        """
        Return the reduced density matrix of the data qubits by
        tracing out the ancillas.  Returns 2^N_DATA amplitudes (unnormalised
        state is fine – we only compute fidelity ratios).
        """
        s = self.state.reshape([2]*self.n)
        # Sum over ancilla indices
        for _ in range(N_ANCILLA):
            s = np.sum(np.abs(s)**2, axis=-1)   # trace out last axis
        return np.sqrt(s).flatten()             # approximate amplitudes


