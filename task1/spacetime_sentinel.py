def make_spacetime_checks(dt: int = 2) -> List[SpacetimeCheck]:
    """
    Generate the list of Controlled-Pauli spacetime checks.

    Each ancilla qubit monitors one data qubit over a window of `dt` time
    layers.  The pattern:
      ancilla 0 → data 0 (Z-check)   | t = 0, dt
      ancilla 1 → data 1 (X-check)   | t = 1, 1+dt
      ancilla 2 → data 2 (Z-check)   | t = 0, dt
      ancilla 3 → data 3 (X-check)   | t = 1, 1+dt

    Increasing `dt` = wider spacetime separation = more time for errors to
    become detectable, but also more idle decoherence between checks.
    """
    checks = [
        SpacetimeCheck(0, 0, "Z", 0),
        SpacetimeCheck(0, 0, "Z", dt),
        SpacetimeCheck(1, 1, "X", 1),
        SpacetimeCheck(1, 1, "X", 1 + dt),
        SpacetimeCheck(2, 2, "Z", 0),
        SpacetimeCheck(2, 2, "Z", dt),
        SpacetimeCheck(3, 3, "X", 1),
        SpacetimeCheck(3, 3, "X", 1 + dt),
    ]
    return checks


def _apply_ansatz_layer(engine: SpacetimeSyndromeEngine,
                        layer: int, rng: np.random.Generator,
                        mode: str):
    """
    Apply one layer of the hardware-efficient ansatz to data qubits 0-3.

    Each layer consists of:
      1. Parameterised Ry rotations on every data qubit
      2. A CNOT entangling ladder (0→1, 2→3, 1→2)
      3. Optional T-gate injection depending on `mode`

    mode = "clifford"  → no T-gates
    mode = "naive"     → T on qubit 1 (inside active X-check window – bad!)
    mode = "zsafe"     → T on qubit 0 (only Z-checks around it – commutes!)
    """
    angles = rng.uniform(0, 2*np.pi, N_DATA)

    # Ry rotations
    for q in range(N_DATA):
        engine.apply_1q(engine._Ry(angles[q]), q)

    # CNOT entangling layer
    engine.apply_cx(0, 1)
    engine.apply_cx(2, 3)
    engine.apply_cx(1, 2)

    # T-gate injection
    if mode == "naive":
        # T on qubit 1 – which is INSIDE an active X-check window.
        # X and T do NOT commute (T is non-Clifford), so this scrambles
        # the syndrome and causes check failures → lower fidelity.
        engine.apply_1q(engine._T, 1)
    elif mode == "zsafe":
        # T on qubit 0 – only Z-checks are active here.
        # Z and T DO commute (T = diag(1, e^{iπ/4}) commutes with Z = diag(1,-1))
        # so the syndrome is unaffected → preserved fidelity.
        engine.apply_1q(engine._T, 0)
    # "clifford" → no T


def apply_depolarising_noise(engine: SpacetimeSyndromeEngine,
                              p1: float, rng: np.random.Generator):
    """
    Apply single-qubit depolarising noise to each data qubit.
    With probability p1: apply a random Pauli (I/X/Y/Z).
    This is our built-in noise model fallback.
    """
    paulis = [engine._X, engine._Y, engine._Z]
    for q in range(N_DATA):
        if rng.random() < p1:
            gate = paulis[rng.integers(0, 3)]
            engine.apply_1q(gate, q)


