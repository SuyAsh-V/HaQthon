@dataclass
class ExperimentResult:
    mode:          str
    dt:            int
    fidelity:      float
    yield_rate:    float        # fraction of shots that passed post-selection
    n_shots:       int
    n_accepted:    int
    run_time_s:    float


def run_experiment(mode: str = "clifford",
                   dt: int = 2,
                   shots: int = SHOTS,
                   seed: int = SEED) -> ExperimentResult:
    """
    Full experiment pipeline for one (mode, dt) configuration.

    Steps:
      1. Build spacetime checks for this dt.
      2. For each shot:
         a. Prepare ancillas in |+⟩ (so they can detect Z-type errors).
         b. Run N_LAYERS ansatz layers, injecting checks at their assigned
            time layers, and adding noise after each layer.
         c. Measure ancillas → syndrome string.
         d. Post-selection: accept shot only if all syndromes are 0 (clean).
      3. Compute fidelity = overlap of accepted data states with ideal state.
    """
    t_start = time.perf_counter()
    rng     = np.random.default_rng(seed)
    checks  = make_spacetime_checks(dt)
    N_LAYERS = max(c.t_layer for c in checks) + 2

    # ── Ideal state (noise-free, Clifford only) ──────────────────────────
    ideal_engine = SpacetimeSyndromeEngine(N_TOTAL, seed=seed)
    ideal_rng    = np.random.default_rng(seed)
    for layer in range(N_LAYERS):
        _apply_ansatz_layer(ideal_engine, layer, ideal_rng, "clifford")
    ideal_state = ideal_engine.state[:2**N_DATA].copy()
    norm = np.linalg.norm(ideal_state)
    if norm > 1e-12:
        ideal_state /= norm

    # ── Shot loop ────────────────────────────────────────────────────────
    overlaps_accepted = []
    n_accepted = 0

    for shot in range(shots):
        shot_seed = seed + shot * 997           # deterministic per-shot seed
        eng = SpacetimeSyndromeEngine(N_TOTAL, seed=shot_seed)
        shot_rng = np.random.default_rng(shot_seed)

        # Prepare ancillas in |+⟩ for Z-syndrome sensitivity
        for a in range(N_ANCILLA):
            eng.apply_1q(eng._H, N_DATA + a)

        # Run layers, fire checks at their scheduled time layer
        check_map: Dict[int, List[SpacetimeCheck]] = defaultdict(list)
        for c in checks:
            check_map[c.t_layer].append(c)

        syndrome_clean = True
        for layer in range(N_LAYERS):
            # Apply ansatz
            _apply_ansatz_layer(eng, layer, shot_rng, mode)
            # Apply noise
            apply_depolarising_noise(eng, P1_DEPOL * (1 + layer*0.1), shot_rng)

            # Fire any checks scheduled at this layer
            if layer in check_map:
                for chk in check_map[layer]:
                    eng.apply_check(chk)

        # Measure ancillas (with readout error)
        syndrome = eng.measure_ancillas(readout_err=P_READOUT)

        # Post-selection: all ancillas must be |0⟩ after Hadamard basis → "0000"
        if syndrome != "0" * N_ANCILLA:
            continue                            # discard corrupted shot

        # Compute fidelity of this shot's data state vs ideal
        data_amp = eng.state[:2**N_DATA]
        norm_d = np.linalg.norm(data_amp)
        if norm_d > 1e-12:
            data_amp /= norm_d
        overlap = abs(np.dot(ideal_state.conj(), data_amp))**2
        overlaps_accepted.append(overlap)
        n_accepted += 1

    fidelity   = float(np.mean(overlaps_accepted)) if overlaps_accepted else 0.0
    yield_rate = n_accepted / shots

    return ExperimentResult(
        mode       = mode,
        dt         = dt,
        fidelity   = fidelity,
        yield_rate = yield_rate,
        n_shots    = shots,
        n_accepted = n_accepted,
        run_time_s = time.perf_counter() - t_start,
    )


