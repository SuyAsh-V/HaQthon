# 6. EXPERIMENT 2 – SPACETIME SEPARATION Δt SWEEP
# ─────────────────────────────────────────────────────────────────────────────

def experiment_2_dt_sweep() -> Dict[str, List]:
    """
    Sweep Δt from 2 to 12 for each mode.

    Scientific insight:
      Small Δt → checks fire quickly, catch errors early, but narrow window
                 means high-frequency errors sneak through between checks.
      Large Δt → wider window catches slow errors but more idle decoherence
                 accumulates, reducing fidelity especially for T-doped modes.

    The Z-Safe mode degrades more gracefully than Naive because its T-gates
    do not corrupt the syndrome at any Δt.
    """
    print("=" * 60)
    print("EXPERIMENT 2: Spacetime Separation Δt Sweep")
    print("=" * 60)
    data = {m: {"dt": [], "fidelity": [], "yield": []}
            for m in ["clifford", "naive", "zsafe"]}

    for dt in DT_VALUES:
        print(f"  Δt = {dt:2d}", end="", flush=True)
        for mode in ["clifford", "naive", "zsafe"]:
            r = run_experiment(mode=mode, dt=dt, shots=SHOTS//2, seed=SEED+dt)
            data[mode]["dt"].append(dt)
            data[mode]["fidelity"].append(r.fidelity)
            data[mode]["yield"].append(r.yield_rate)
            print(f"  [{mode[:3]} F={r.fidelity:.3f}]", end="", flush=True)
        print()
    print()
    return data


