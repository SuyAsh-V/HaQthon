def experiment_1_tdoping() -> Dict[str, ExperimentResult]:
    """
    Compare the three T-doping strategies at a fixed Δt = 4.

    Scientific insight:
      Clifford   → clean syndromes, high fidelity baseline
      Naive      → T inside active X-check window → syndrome scrambled → lower fidelity
      Z-Safe     → T placed where Z-checks commute with T → fidelity near Clifford
    """
    print("=" * 60)
    print("EXPERIMENT 1: Clifford vs Naive vs Z-Safe T-Doping  (Δt=4)")
    print("=" * 60)
    results = {}
    for mode in ["clifford", "naive", "zsafe"]:
        print(f"  Running {mode:10s} ...", end=" ", flush=True)
        r = run_experiment(mode=mode, dt=4, shots=SHOTS, seed=SEED)
        results[mode] = r
        print(f"Fidelity={r.fidelity:.4f}  Yield={r.yield_rate:.3f}  "
              f"({r.run_time_s:.1f}s)")
    print()
    return results


