# ─────────────────────────────────────────────────────────────────────────────
# 1.  PLANAR SURFACE CODE GEOMETRY
# ─────────────────────────────────────────────────────────────────────────────

class PlanarCode:
    """
    Distance-d planar surface code on a (2d−1)×(2d−1) grid.

    Grid convention
    ---------------
    Site (i, j) with i+j even  → DATA qubit.
    i even,  j odd             → Z-type check ancilla (detects X errors).
    i odd,   j even            → X-type check ancilla (detects Z errors).

    For d=3 the grid is 5×5:
      13 data qubits, 6 Z-checks, 6 X-checks.

    Logical operators
    -----------------
    Logical X̄  = X on every data qubit in row 0.
    Logical Z̄  = Z on every data qubit in column 0.

    Parity-check matrices
    ---------------------
    Hz  : (n_Z_checks × n_data)  binary matrix; Hz[s,q]=1 if Z-check s
          acts on data qubit q.  Hz detects X errors (syndrome sx = Hz·ex mod 2).
    Hx  : (n_X_checks × n_data)  similarly for X-checks / Z errors.
    """

    def __init__(self, d: int = 3) -> None:
        self.d = d
        self.L = 2 * d - 1          # grid side length

        # ── enumerate sites ──────────────────────────────────────────
        self.data_sites:    List[Tuple[int,int]] = []
        self.z_check_sites: List[Tuple[int,int]] = []
        self.x_check_sites: List[Tuple[int,int]] = []

        for i in range(self.L):
            for j in range(self.L):
                if (i + j) % 2 == 0:
                    self.data_sites.append((i, j))
                elif i % 2 == 0 and j % 2 == 1:
                    self.z_check_sites.append((i, j))
                elif i % 2 == 1 and j % 2 == 0:
                    self.x_check_sites.append((i, j))

        self.n_data    = len(self.data_sites)
        self.n_z_check = len(self.z_check_sites)
        self.n_x_check = len(self.x_check_sites)

        # index maps
        self._data_idx:    Dict[Tuple[int,int], int] = {
            s: k for k, s in enumerate(self.data_sites)
        }
        self._z_check_idx: Dict[Tuple[int,int], int] = {
            s: k for k, s in enumerate(self.z_check_sites)
        }
        self._x_check_idx: Dict[Tuple[int,int], int] = {
            s: k for k, s in enumerate(self.x_check_sites)
        }

        # ── build parity-check matrices ───────────────────────────────
        self.Hz = self._build_H(self.z_check_sites)
        self.Hx = self._build_H(self.x_check_sites)

        # ── logical operators (binary vectors, length n_data) ─────────
        # Logical X̄: X on row 0 data qubits
        self.lx = np.array(
            [1 if s[0] == 0 else 0 for s in self.data_sites], dtype=np.uint8
        )
        # Logical Z̄: Z on column 0 data qubits
        self.lz = np.array(
            [1 if s[1] == 0 else 0 for s in self.data_sites], dtype=np.uint8
        )

        # Precompute neighbour lists for network construction
        self._data_z_neighbours = self._build_neighbours(self.z_check_sites)
        self._data_x_neighbours = self._build_neighbours(self.x_check_sites)

    # ── internal helpers ─────────────────────────────────────────────────

    def _neighbours(self, ci: int, cj: int) -> List[Tuple[int,int]]:
        """Return in-grid data-qubit neighbours of a check at (ci, cj)."""
        dirs = [(-1,0),(1,0),(0,-1),(0,1)]
        nbrs = []
        for di, dj in dirs:
            ni, nj = ci+di, cj+dj
            if 0 <= ni < self.L and 0 <= nj < self.L:
                if (ni+nj) % 2 == 0:          # it's a data site
                    nbrs.append((ni, nj))
        return nbrs

    def _build_H(self, check_sites: List[Tuple[int,int]]) -> np.ndarray:
        H = np.zeros((len(check_sites), self.n_data), dtype=np.uint8)
        for si, (ci, cj) in enumerate(check_sites):
            for nbr in self._neighbours(ci, cj):
                H[si, self._data_idx[nbr]] = 1
        return H

    def _build_neighbours(
        self, check_sites: List[Tuple[int,int]]
    ) -> List[List[int]]:
        """For each check, list of data-qubit indices it touches."""
        return [
            [self._data_idx[n] for n in self._neighbours(ci, cj)]
            for (ci, cj) in check_sites
        ]

    # ── public geometry queries ──────────────────────────────────────────

    def data_qubit_index(self, i: int, j: int) -> int:
        return self._data_idx[(i, j)]

    def checks_on_qubit(self, q: int) -> Tuple[List[int], List[int]]:
        """
        Returns (z_check_indices, x_check_indices) that include qubit q.
        Used when building the tensor network.
        """
        zs = [s for s, row in enumerate(self.Hz) if row[q]]
        xs = [s for s, row in enumerate(self.Hx) if row[q]]
        return zs, xs


# ─────────────────────────────────────────────────────────────────────────────
# 2.  GF(2) GAUSSIAN ELIMINATION
# ─────────────────────────────────────────────────────────────────────────────

def gf2_solve(H: np.ndarray, s: np.ndarray) -> np.ndarray:
    """
    Solve  H · x = s  over GF(2) using Gaussian elimination.

    Finds ANY particular solution e0 consistent with the syndrome s.
    If H is under-determined (more columns than rows, as expected for
    a surface code) many solutions exist; we return just one.

    Parameters
    ----------
    H : (m × n) binary matrix, dtype uint8
    s : (m,)   binary syndrome vector

    Returns
    -------
    e0 : (n,) binary solution vector (uint8), or zeros if s=0.

    Raises
    ------
    ValueError if system is inconsistent (should not happen for valid syndromes).
    """
    m, n = H.shape
    # Augmented matrix [H | s]
    aug = np.hstack([H.copy(), s.reshape(-1, 1)]).astype(np.uint8)

    pivot_cols: List[int] = []
    row = 0
    for col in range(n):
        # Find pivot
        pivot = None
        for r in range(row, m):
            if aug[r, col]:
                pivot = r
                break
        if pivot is None:
            continue
        # Swap
        aug[[row, pivot]] = aug[[pivot, row]]
        pivot_cols.append(col)
        # Eliminate
        for r in range(m):
            if r != row and aug[r, col]:
                aug[r] = (aug[r] + aug[row]) % 2
        row += 1

    # Back-substitute: free variables = 0
    x = np.zeros(n, dtype=np.uint8)
    for pc, c in enumerate(pivot_cols):
        x[c] = aug[pc, n]

    # Verify
    check = H @ x % 2
    if not np.array_equal(check, s % 2):
        # Inconsistent – return zero vector (happens with measurement errors;
        # caller should handle gracefully)
        return np.zeros(n, dtype=np.uint8)

    return x


# ─────────────────────────────────────────────────────────────────────────────
# 3.  NOISE MODEL
# ─────────────────────────────────────────────────────────────────────────────

@dataclass
class NoiseParams:
    """All parameters for the biased X/Z + heralded-erasure noise model."""
    p_x: float = 0.10      # X-error probability per qubit
    p_z: float = 0.01      # Z-error probability per qubit  (= p_x / 10)
    p_e: float = 0.05      # heralded erasure probability


def priors(
    n: int,
    params: NoiseParams,
    erased: Optional[np.ndarray] = None,
) -> np.ndarray:
    """
    Build per-qubit prior probability table P[q, x_bit, z_bit].

    For a normal qubit:
      P[q, 0, 0] = (1-p_x)(1-p_z)  (I)
      P[q, 1, 0] = p_x * (1-p_z)   (X)
      P[q, 0, 1] = (1-p_x) * p_z   (Z)
      P[q, 1, 1] = p_x * p_z       (Y = X·Z)

    For an erased qubit (if erased[q] is True):
      P[q, x, z] = 0.25 for all (x,z)  – uniform over I/X/Y/Z.

    Parameters
    ----------
    n       : number of data qubits
    params  : NoiseParams
    erased  : bool array length n (None = no erasures)

    Returns
    -------
    P : (n, 2, 2) float array
    """
    px, pz = params.p_x, params.p_z
    if erased is None:
        erased = np.zeros(n, dtype=bool)

    P = np.zeros((n, 2, 2), dtype=float)
    for q in range(n):
        if erased[q]:
            P[q] = 0.25
        else:
            P[q, 0, 0] = (1 - px) * (1 - pz)
            P[q, 1, 0] = px       * (1 - pz)
            P[q, 0, 1] = (1 - px) * pz
            P[q, 1, 1] = px       * pz
    return P


def sample_error(
    code: PlanarCode,
    params: NoiseParams,
    rng: np.random.Generator,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Sample a random error from the biased noise model.

    Returns
    -------
    ex      : (n,) binary X-error vector
    ez      : (n,) binary Z-error vector
    erased  : (n,) bool array – True where erasure occurred
    """
    n = code.n_data
    erased = rng.random(n) < params.p_e

    ex = np.zeros(n, dtype=np.uint8)
    ez = np.zeros(n, dtype=np.uint8)

    for q in range(n):
        if erased[q]:
            # Uniform random Pauli: I(0,0), X(1,0), Z(0,1), Y(1,1)
            bits = rng.integers(0, 2, size=2)
            ex[q], ez[q] = bits[0], bits[1]
        else:
            if rng.random() < params.p_x:
                ex[q] = 1
            if rng.random() < params.p_z:
                ez[q] = 1

    return ex, ez, erased


# ─────────────────────────────────────────────────────────────────────────────
# 4.  TENSOR NETWORK CONSTRUCTION
# ─────────────────────────────────────────────────────────────────────────────

def build_network(
    code: PlanarCode,
    P: np.ndarray,
    f_x: np.ndarray,
    f_z: np.ndarray,
) -> List[List[np.ndarray]]:
    """
    Build the 2D tensor network for computing the coset probability.

    Each DATA site (i,j) in the grid holds a rank-4 tensor T with legs
    ordered (up, right, down, left), each of bond dimension 2 (or 1 if
    on the boundary).

    Each CHECK site holds a COPY/delta tensor: legs are equal when the
    stabiliser is "multiplied in" (leg value = 1) → parity check.

    The network value (after full contraction) equals the sum of
    P(E · f) over all elements E of the stabiliser group, which is the
    coset probability needed for maximum-likelihood decoding.

    Parameters
    ----------
    code  : PlanarCode
    P     : (n, 2, 2) prior array (from priors())
    f_x   : (n,) binary X-part of the fixed Pauli for this coset
    f_z   : (n,) binary Z-part of the fixed Pauli for this coset

    Returns
    -------
    grid  : L×L list-of-lists of numpy arrays; None at non-site positions.

    Implementation note
    -------------------
    We represent the 2D network as a plain Python list-of-lists grid of
    small numpy arrays. The boundary-MPS contraction in `compress` then
    sweeps left→right through the grid columns.
    """
    L = code.L
    grid: List[List[Optional[np.ndarray]]] = [[None]*L for _ in range(L)]

    # ── Data tensors ──────────────────────────────────────────────────
    for q, (i, j) in enumerate(code.data_sites):
        z_checks, x_checks = code.checks_on_qubit(q)
        # Legs: up(i-1,j), right(i,j+1), down(i+1,j), left(i,j-1)
        # Dimension = 2 if a check lives in that direction, else 1
        up_dim    = 2 if (i-1 >= 0 and (i-1+j) % 2 != 0) else 1
        right_dim = 2 if (j+1 <  L and (i+j+1) % 2 != 0) else 1
        down_dim  = 2 if (i+1 <  L and (i+1+j) % 2 != 0) else 1
        left_dim  = 2 if (j-1 >= 0 and (i+j-1) % 2 != 0) else 1

        T = np.zeros((up_dim, right_dim, down_dim, left_dim), dtype=float)

        # Sum over which stabilisers (neighbouring checks) flip f
        for su in range(up_dim):
            for sr in range(right_dim):
                for sd in range(down_dim):
                    for sl in range(left_dim):
                        # The check-leg values tell us which checks multiply in.
                        # An X-check neighbour contributes an extra Z flip on this qubit.
                        # A Z-check neighbour contributes an extra X flip.
                        extra_x = 0
                        extra_z = 0
                        # Walk all 4 check neighbours and accumulate
                        chk_legs = {"up": su, "right": sr, "down": sd, "left": sl}
                        for direction, leg_val in chk_legs.items():
                            if leg_val == 0:
                                continue
                            # Find check at (i+di, j+dj)
                            di, dj = {"up":(-1,0),"right":(0,1),
                                       "down":(1,0),"left":(0,-1)}[direction]
                            ci, cj = i+di, j+dj
                            if 0 <= ci < L and 0 <= cj < L:
                                if ci % 2 == 0 and cj % 2 == 1:
                                    # Z-check → flips X bit of this qubit
                                    extra_x ^= 1
                                elif ci % 2 == 1 and cj % 2 == 0:
                                    # X-check → flips Z bit of this qubit
                                    extra_z ^= 1

                        eff_x = int(f_x[q]) ^ extra_x
                        eff_z = int(f_z[q]) ^ extra_z
                        T[su, sr, sd, sl] = P[q, eff_x, eff_z]

        grid[i][j] = T

    # ── Check (COPY) tensors ─────────────────────────────────────────
    for (ci, cj) in code.z_check_sites + code.x_check_sites:
        # weight = number of data-qubit neighbours = number of legs
        nbrs = code._neighbours(ci, cj)
        n_legs = len(nbrs)
        # COPY tensor: value 1 iff all legs equal (parity check)
        shape = (2,) * n_legs
        C = np.zeros(shape, dtype=float)
        for idx in np.ndindex(*shape):
            if sum(idx) % 2 == 0:         # even parity = stabiliser in / out
                C[idx] = 1.0
        grid[ci][cj] = C

    return grid


# ─────────────────────────────────────────────────────────────────────────────
# 5.  BOUNDARY MPS CONTRACTION  (column-by-column sweep)
# ─────────────────────────────────────────────────────────────────────────────

def compress(
    grid: List[List[Optional[np.ndarray]]],
    L: int,
    eps: float = 1e-2,
    chi_max: int = 64,
) -> Tuple[float, float, float, int]:
    """
    Contract the 2D tensor network using a boundary MPS approach.

    Algorithm
    ---------
    1. Start with MPS = identity (trivial left boundary).
    2. For each column j = 0 … L-1:
       a. Absorb column j as an MPO into the current MPS by contracting
          each row's tensor with the corresponding MPS site.
       b. Right-canonicalise via QR decomposition.
       c. Sweep SVDs left→right with DYNAMIC truncation:
          keep singular values s > ε·s_max, capped at chi_max.
       d. Normalise (track log-scale to avoid underflow).
    3. Contract the final MPS to a scalar.

    Returns
    -------
    log_prob     : log of the unnormalised coset probability
    trunc_error  : total discarded singular-value weight (normalised)
    max_chi      : maximum bond dimension actually used
    n_svd        : number of SVD truncation steps performed
    """
    # Represent the MPS as a list of (D_left, d_phys, D_right) tensors.
    # Initially: D_left=1, d_phys=1, D_right=1.
    mps: List[np.ndarray] = [np.ones((1, 1, 1), dtype=float) for _ in range(L)]

    log_norm    = 0.0
    trunc_error = 0.0
    max_chi     = 1
    n_svd       = 0

    for j in range(L):       # sweep columns left → right
        # ── absorb column j into MPS ──────────────────────────────────
        new_mps: List[np.ndarray] = []
        for i in range(L):
            tensor = grid[i][j]
            mps_t  = mps[i]               # shape (Dl, d, Dr)
            Dl, d, Dr = mps_t.shape

            if tensor is None:
                new_mps.append(mps_t)
                continue

            # Contract physical index of MPS with left leg of site tensor.
            # Site tensor shape varies; treat it as (bond_left, *other_legs).
            # We flatten "other_legs" into a single new physical index.
            T = tensor  # varies in rank
            if T.ndim == 0:
                # scalar site (fully contracted)
                new_t = mps_t * float(T)
                new_mps.append(new_t)
                continue

            # Flatten T to (d_left, d_rest)
            d_left = T.shape[0] if T.ndim > 0 else 1
            d_rest = T.size // (d_left if d_left > 0 else 1)
            if d_left != d:
                # Dimension mismatch → treat as scalar 1
                new_mps.append(mps_t)
                continue

            T2d = T.reshape(d_left, d_rest)
            # Contract: new[Dl, d_rest, Dr] = sum_d mps[Dl,d,Dr] * T2d[d, d_rest]
            new_t = np.einsum("idk,dj->ijk", mps_t, T2d)
            new_mps.append(new_t)

        mps = new_mps

        # ── right-canonicalise via QR ─────────────────────────────────
        for i in range(L - 1, 0, -1):
            t = mps[i]
            Dl, d, Dr = t.shape
            mat = t.reshape(Dl, d * Dr)
            Q, R = np.linalg.qr(mat.T)       # Q: (d*Dr, k), R: (k, Dl)
            Q = Q.T; R = R.T                  # Q: (k, d*Dr), R: (Dl, k)
            k = Q.shape[0]
            mps[i] = Q.reshape(k, d, Dr)
            mps[i-1] = np.einsum("ijk,kl->ijl", mps[i-1], R)

        # ── SVD sweep left→right with dynamic truncation ──────────────
        for i in range(L - 1):
            t = mps[i]
            Dl, d, Dr = t.shape
            mat = t.reshape(Dl * d, Dr)
            if mat.size == 0:
                continue
            try:
                U, s_vals, Vt = np.linalg.svd(mat, full_matrices=False)
            except np.linalg.LinAlgError:
                continue

            # Dynamic truncation threshold
            s_max = s_vals[0] if len(s_vals) > 0 else 1.0
            if s_max < 1e-300:
                continue
            threshold = eps * s_max
            keep_mask = s_vals > threshold
            # Enforce chi_max cap
            if keep_mask.sum() > chi_max:
                keep_mask[chi_max:] = False

            keep = int(keep_mask.sum())
            if keep == 0:
                keep = 1   # always keep at least one

            # Accumulate truncation error
            discarded = np.sum(s_vals[keep:]**2)
            total_sq  = np.sum(s_vals**2)
            if total_sq > 1e-300:
                trunc_error += discarded / total_sq
            n_svd += 1
            max_chi = max(max_chi, keep)

            # Truncate
            U     = U[:, :keep]
            s_vals_k = s_vals[:keep]
            Vt    = Vt[:keep, :]

            mps[i]   = U.reshape(Dl, d, keep)
            mps[i+1] = np.einsum("i,ij,jkl->ikl",
                                  s_vals_k, Vt,
                                  mps[i+1].reshape(Dr, *mps[i+1].shape[1:])
                                  if mps[i+1].shape[0] == Dr
                                  else mps[i+1])

        # ── normalise to avoid float underflow ─────────────────────────
        norms = [np.linalg.norm(t) for t in mps if t is not None]
        total_norm = float(np.prod([n for n in norms if n > 1e-300]))
        if total_norm > 1e-300:
            log_norm += np.log(total_norm)
            for i in range(L):
                if mps[i] is not None:
                    norm_i = np.linalg.norm(mps[i])
                    if norm_i > 1e-300:
                        mps[i] = mps[i] / norm_i

    # ── contract final MPS to scalar ─────────────────────────────────
    result = np.array([[[1.0]]])
    for t in mps:
        if t is None:
            continue
        Dl, d, Dr = t.shape
        # Contract right leg of result with left leg of t
        r_shape = result.shape
        if r_shape[-1] != Dl:
            result = np.ones((1, 1, 1))
            break
        result = np.einsum("ijk,klm->ijlm", result, t)
        s = result.shape
        result = result.reshape(s[0], s[1]*s[2], s[3])

    scalar = float(np.sum(np.abs(result)))

    return log_norm + (np.log(scalar) if scalar > 1e-300 else -1e10), \
           trunc_error / max(n_svd, 1), \
           float(max_chi), \
           n_svd


# ─────────────────────────────────────────────────────────────────────────────
# 6.  FOUR-ELEMENT ARRAY & DECODING
# ─────────────────────────────────────────────────────────────────────────────

# Logical representatives: (lx_coeff, lz_coeff)
# I  → (0, 0),  X̄ → (1, 0),  Z̄ → (0, 1),  Ȳ → (1, 1)
LOGICAL_CLASSES = [(0,0), (1,0), (0,1), (1,1)]
LOGICAL_NAMES   = ["I", "X̄", "Z̄", "Ȳ"]


def contract(
    code: PlanarCode,
    P: np.ndarray,
    e0_x: np.ndarray,
    e0_z: np.ndarray,
    eps: float = 1e-2,
    chi_max: int = 64,
) -> Tuple[np.ndarray, float, float, int]:
    """
    Compute the four-element probability array [P(I), P(X̄), P(Z̄), P(Ȳ)].

    For each logical class L = (lx_c, lz_c):
      f_x = e0_x ⊕ lx_c * lx
      f_z = e0_z ⊕ lz_c * lz
      Build 2D network for (f_x, f_z) and contract → log P(L).

    Returns
    -------
    probs        : (4,) normalised probability array
    trunc_error  : mean truncation error across 4 contractions
    max_chi      : max bond dimension used
    n_svd_total  : total SVD steps
    """
    log_probs   = np.zeros(4, dtype=float)
    trunc_errs  = []
    max_chis    = []
    n_svds      = 0

    for k, (lx_c, lz_c) in enumerate(LOGICAL_CLASSES):
        f_x = (e0_x ^ (lx_c * code.lx)) % 2
        f_z = (e0_z ^ (lz_c * code.lz)) % 2
        net = build_network(code, P, f_x, f_z)
        lp, te, mc, ns = compress(net, code.L, eps=eps, chi_max=chi_max)
        log_probs[k]  = lp
        trunc_errs.append(te)
        max_chis.append(mc)
        n_svds += ns

    # Normalise in log-space for numerical stability
    log_probs -= np.max(log_probs)
    probs = np.exp(log_probs)
    probs /= probs.sum()

    return (probs,
            float(np.mean(trunc_errs)),
            float(max(max_chis)),
            n_svds)


def decode_tn(
    code: PlanarCode,
    sx: np.ndarray,
    sz: np.ndarray,
    P: np.ndarray,
    eps: float = 1e-2,
    chi_max: int = 64,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray, float, float, int]:
    """
    Full tensor-network decode pipeline.

    1. Find any recovery e0 consistent with (sx, sz) via GF(2) solve.
    2. Compute 4-element array via `contract`.
    3. Return the maximum-likelihood correction C = e0 ⊕ L*.

    Returns
    -------
    C_x, C_z   : correction operator (binary arrays)
    probs       : 4-element array [P(I), P(X̄), P(Z̄), P(Ȳ)]
    trunc_error, max_chi, n_svd
    """
    e0_x = gf2_solve(code.Hz, sx)
    e0_z = gf2_solve(code.Hx, sz)

    probs, te, mc, ns = contract(code, P, e0_x, e0_z, eps=eps, chi_max=chi_max)
    best = int(np.argmax(probs))
    lx_c, lz_c = LOGICAL_CLASSES[best]

    C_x = (e0_x ^ (lx_c * code.lx)) % 2
    C_z = (e0_z ^ (lz_c * code.lz)) % 2

    return C_x, C_z, probs, float(te), float(mc), ns


# ─────────────────────────────────────────────────────────────────────────────
# 7.  BRUTE-FORCE EXACT DECODER  (validation reference, d=3 only)
# ─────────────────────────────────────────────────────────────────────────────

def exact_cosets(
    code: PlanarCode,
    P: np.ndarray,
    e0_x: np.ndarray,
    e0_z: np.ndarray,
) -> np.ndarray:
    """
    Enumerate ALL 2^(n_z_check) × 2^(n_x_check) stabiliser products per
    coset and sum their probabilities exactly.

    This is the ground-truth reference. Only feasible for small d (d=3
    has 4096 stabiliser elements total per coset).

    Returns
    -------
    probs : (4,) exact probability array, normalised.
    """
    n_stab_x = code.n_z_check    # Z-checks generate X-type stabilisers
    n_stab_z = code.n_x_check    # X-checks generate Z-type stabilisers

    log_probs = np.zeros(4, dtype=np.float64)

    for k, (lx_c, lz_c) in enumerate(LOGICAL_CLASSES):
        f_x = (e0_x ^ (lx_c * code.lx)) % 2
        f_z = (e0_z ^ (lz_c * code.lz)) % 2

        total = 0.0
        # Iterate over all stabiliser products
        for sx_bits in range(2**n_stab_x):
            # X-part of stabiliser: rows of Hz indexed by set bits
            s_x_row = np.zeros(code.n_data, dtype=np.uint8)
            for bit in range(n_stab_x):
                if (sx_bits >> bit) & 1:
                    s_x_row = (s_x_row + code.Hz[bit]) % 2

            for sz_bits in range(2**n_stab_z):
                s_z_row = np.zeros(code.n_data, dtype=np.uint8)
                for bit in range(n_stab_z):
                    if (sz_bits >> bit) & 1:
                        s_z_row = (s_z_row + code.Hx[bit]) % 2

                # Element of coset: f ⊕ stabiliser
                e_x = (f_x + s_x_row) % 2
                e_z = (f_z + s_z_row) % 2

                # Probability = product over qubits
                prob = 1.0
                for q in range(code.n_data):
                    prob *= P[q, int(e_x[q]), int(e_z[q])]
                total += prob

        log_probs[k] = np.log(total) if total > 0 else -1e300

    log_probs -= np.max(log_probs)
    probs = np.exp(log_probs)
    probs /= probs.sum()
    return probs


# ─────────────────────────────────────────────────────────────────────────────
# 8.  MONTE-CARLO FIDELITY RUNNER
# ─────────────────────────────────────────────────────────────────────────────

def check_logical_failure(
    code: PlanarCode,
    C_x: np.ndarray,
    C_z: np.ndarray,
    E_x: np.ndarray,
    E_z: np.ndarray,
) -> bool:
    """
    Check if residual R = C · E_true is a logical failure.

    R is a logical failure if it anticommutes with X̄ or Z̄.

    Anticommutation:
      R_x · Z̄ (mod 2) = R_x · lz → non-zero = anticommute
      R_z · X̄ (mod 2) = R_z · lx → non-zero = anticommute
    """
    R_x = (C_x ^ E_x) % 2
    R_z = (C_z ^ E_z) % 2

    # R anticommutes with Z̄  iff  (sum of R_x on lz support) is odd
    anticommute_z = int(np.dot(R_x, code.lz)) % 2
    # R anticommutes with X̄  iff  (sum of R_z on lx support) is odd
    anticommute_x = int(np.dot(R_z, code.lx)) % 2

    return bool(anticommute_x or anticommute_z)


@dataclass
class RunResult:
    """Aggregated result from a Monte-Carlo fidelity run."""
    n_shots:       int
    n_failures:    int
    fidelity:      float
    fidelity_se:   float          # standard error
    mean_confidence: float
    mean_trunc_error: float
    mean_chi:      float
    mean_time_ms:  float
    score:         float          # fidelity_score()
    raw_failures:  List[bool] = field(default_factory=list, repr=False)


def run(
    code: PlanarCode,
    params: NoiseParams,
    n_shots: int = 1000,
    eps: float = 1e-2,
    chi_max: int = 64,
    seed: int = 42,
    erasure_blind: bool = False,
    bias_blind: bool = False,
) -> RunResult:
    """
    Monte-Carlo fidelity estimator.

    Parameters
    ----------
    code          : PlanarCode
    params        : NoiseParams
    n_shots       : number of random errors to decode
    eps           : SVD truncation threshold
    chi_max       : maximum MPS bond dimension
    seed          : RNG seed for reproducibility
    erasure_blind : if True, ignore erasure flags (treat all as normal qubits)
    bias_blind    : if True, use symmetric p = (p_x + p_z)/2 for decoder priors

    Returns
    -------
    RunResult with fidelity, standard error, and performance metrics.
    """
    rng = np.random.default_rng(seed)
    failures    = []
    confidences = []
    trunc_errs  = []
    chis        = []
    times_ms    = []

    for _ in range(n_shots):
        # ── sample error ──────────────────────────────────────────────
        E_x, E_z, erased = sample_error(code, params, rng)

        # ── compute syndrome ──────────────────────────────────────────
        sx = (code.Hz @ E_x) % 2
        sz = (code.Hx @ E_z) % 2

        # ── build decoder priors ──────────────────────────────────────
        if bias_blind:
            p_sym = (params.p_x + params.p_z) / 2
            bp = NoiseParams(p_x=p_sym, p_z=p_sym, p_e=params.p_e)
            P = priors(code.n_data, bp,
                       erased=None if erasure_blind else erased)
        else:
            P = priors(code.n_data, params,
                       erased=None if erasure_blind else erased)

        # ── decode ────────────────────────────────────────────────────
        t0 = time.perf_counter()
        C_x, C_z, probs, te, mc, _ = decode_tn(
            code, sx, sz, P, eps=eps, chi_max=chi_max
        )
        t_ms = (time.perf_counter() - t0) * 1000

        # ── check for logical failure ─────────────────────────────────
        failed = check_logical_failure(code, C_x, C_z, E_x, E_z)
        failures.append(failed)
        confidences.append(float(np.max(probs)))
        trunc_errs.append(te)
        chis.append(mc)
        times_ms.append(t_ms)

    n_fail   = sum(failures)
    n_ok     = n_shots - n_fail
    F        = n_ok / n_shots
    F_se     = float(np.sqrt(F * (1 - F) / n_shots))
    t_budget = 10.0   # ms
    mean_t   = float(np.mean(times_ms))
    score    = fidelity_score(F, mean_t, t_budget)

    return RunResult(
        n_shots          = n_shots,
        n_failures       = n_fail,
        fidelity         = F,
        fidelity_se      = F_se,
        mean_confidence  = float(np.mean(confidences)),
        mean_trunc_error = float(np.mean(trunc_errs)),
        mean_chi         = float(np.mean(chis)),
        mean_time_ms     = mean_t,
        score            = score,
        raw_failures     = failures,
    )


def fidelity_score(F: float, t_ms: float, T_budget: float = 10.0) -> float:
    """
    Composite performance score.

    Score = F_logical × min(1, T_budget / t_decode_ms)

    Higher is better. Penalises slow decoders that exceed the latency budget.
    """
    return F * min(1.0, T_budget / max(t_ms, 1e-9))


# ─────────────────────────────────────────────────────────────────────────────
# 9.  QISKIT VALIDATION CHECK
# ─────────────────────────────────────────────────────────────────────────────

def qiskit_check(code: PlanarCode) -> bool:
    """
    Use qiskit.quantum_info.Pauli to verify:
      1. All stabilisers commute with each other.
      2. Both logicals (X̄, Z̄) commute with every stabiliser.
      3. X̄ and Z̄ anticommute with each other.

    Prints results and returns True if all checks pass.
    Falls back gracefully if Qiskit is not installed.
    """
    print("\n── Qiskit Algebra Verification ──────────────────────────────")
    try:
        from qiskit.quantum_info import Pauli
    except ImportError:
        print("  Qiskit not installed – skipping verification (SKIP).")
        return True   # don't fail the test suite

    n = code.n_data

    def make_pauli(x_bits: np.ndarray, z_bits: np.ndarray) -> "Pauli":
        # Qiskit Pauli convention: Pauli(z_string + x_string) with LSB first
        x_str = "".join(str(b) for b in reversed(x_bits))
        z_str = "".join(str(b) for b in reversed(z_bits))
        return Pauli(z_str + x_str)   # Qiskit uses 'zx' label convention

    # Build Pauli objects for Z-stabilisers (X-type, from Hz)
    z_stabs = [make_pauli(row, np.zeros(n, dtype=np.uint8))
               for row in code.Hz]
    # Build Pauli objects for X-stabilisers (Z-type, from Hx)
    x_stabs = [make_pauli(np.zeros(n, dtype=np.uint8), row)
               for row in code.Hx]
    all_stabs = z_stabs + x_stabs

    logical_X = make_pauli(code.lx, np.zeros(n, dtype=np.uint8))
    logical_Z = make_pauli(np.zeros(n, dtype=np.uint8), code.lz)

    all_ok = True

    # Check 1: stabilisers commute with each other
    comm_ok = True
    for i, s1 in enumerate(all_stabs):
        for s2 in all_stabs[i+1:]:
            if not s1.commutes(s2):
                print(f"  FAIL: stabilisers {i} and {all_stabs.index(s2)} do not commute!")
                comm_ok = False
    print(f"  Stabilisers commute pairwise: {comm_ok}")
    all_ok = all_ok and comm_ok

    # Check 2: logicals commute with all stabilisers
    lx_comm = all(logical_X.commutes(s) for s in all_stabs)
    lz_comm = all(logical_Z.commutes(s) for s in all_stabs)
    print(f"  Logical X̄ commutes with all stabilisers: {lx_comm}")
    print(f"  Logical Z̄ commutes with all stabilisers: {lz_comm}")
    all_ok = all_ok and lx_comm and lz_comm

    # Check 3: X̄ and Z̄ anticommute
    anticomm = not logical_X.commutes(logical_Z)
    print(f"  X̄ anticommutes with Z̄: {anticomm}")
    all_ok = all_ok and anticomm

    print(f"  → All checks passed: {all_ok}")
    print("─" * 52)
    return all_ok
